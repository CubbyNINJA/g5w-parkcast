"""Tag-rule check and traceability for specs/features (specs/README.md).

    python tools/trace_specs.py           # check, then write docs/spec/TRACEABILITY.md
    python tools/trace_specs.py --check   # check only; exit 1 on any problem
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FEATURES = ROOT / "specs" / "features"
REQS = ROOT / "docs" / "spec" / "REQUIREMENTS.md"
OUT = ROOT / "docs" / "spec" / "TRACEABILITY.md"

TIERS = {"offline", "host", "pc", "unit"}
KINDS = {"normal", "failure", "boundary"}


def known_ids() -> tuple[set[str], set[str]]:
    text = REQS.read_text(encoding="utf-8")
    return set(re.findall(r"^\| (AIR-\d{3}) \|", text, re.M)), set(re.findall(r"^\| (AT-\d{2})\b", text, re.M))


def scenarios() -> list[dict]:
    """(feature, line, name, tags) for every Scenario or Scenario Outline, with feature tags merged."""
    out = []
    for path in sorted(FEATURES.glob("*.feature")):
        feature_tags: set[str] = set()
        pending: set[str] = set()
        for n, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            line = raw.strip()
            if line.startswith("@"):
                pending |= {t[1:] for t in line.split() if t.startswith("@")}
            elif line.startswith("Feature:"):
                feature_tags, pending = pending, set()
            elif re.match(r"Scenario( Outline)?:", line):
                out.append(dict(feature=path.name, line=n, name=line.split(":", 1)[1].strip(),
                                tags=feature_tags | pending))
                pending = set()
            elif line and not line.startswith("#"):
                pending = pending if line.startswith("Examples") else set()
    return out


def check() -> list[str]:
    air, at = known_ids()
    problems = []
    for s in scenarios():
        where = f"{s['feature']}:{s['line']} {s['name']!r}"
        tags = s["tags"]
        reqs = {t for t in tags if t.startswith("AIR-")}
        tests = {t for t in tags if t.startswith("AT-")}
        if not reqs:
            problems.append(f"{where}: no @AIR- requirement tag")
        if not tests:
            problems.append(f"{where}: no @AT- test tag")
        for t in sorted((reqs - air) | (tests - at)):
            problems.append(f"{where}: @{t} isn't in REQUIREMENTS.md")
        for group, name in ((TIERS, "tier"), (KINDS, "kind"), ({t for t in tags if re.fullmatch(r"S\d+", t)}, "slice")):
            found = tags & group if name != "slice" else group
            if len(found) != 1:
                problems.append(f"{where}: needs exactly one {name} tag, found {sorted(found) or 'none'}")
    return problems


def write() -> None:
    rows = scenarios()
    by_req: dict[str, list[str]] = {}
    for s in rows:
        for t in sorted(t for t in s["tags"] if t.startswith("AIR-")):
            by_req.setdefault(t, []).append(f"{s['feature']}:{s['line']}")
    air, _ = known_ids()
    lines = ["# Traceability", "", "Generated by `python tools/trace_specs.py`. Do not edit by hand.", "",
             "| Requirement | Scenarios |", "|---|---|"]
    for r in sorted(air):
        lines.append(f"| {r} | {', '.join(by_req.get(r, [])) or '**none**'} |")
    lines += ["", f"{len(rows)} scenarios in {len(list(FEATURES.glob('*.feature')))} feature files.", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    found = check()
    for p in found:
        print(p)
    if "--check" not in sys.argv:
        write()
        print(f"wrote {OUT.relative_to(ROOT)}")
    sys.exit(1 if found else 0)
